package com.wiseowl.wowcareapp

import android.content.Intent
import io.flutter.Log
import io.flutter.embedding.android.FlutterActivity
import io.flutter.embedding.engine.FlutterEngine
import io.flutter.embedding.engine.plugins.FlutterPlugin
import io.flutter.plugin.common.MethodChannel

// Manual plugin registration that tolerates one plugin's native-init crash.
//
// The default `FlutterActivity.configureFlutterEngine` delegates to
// `io.flutter.plugins.GeneratedPluginRegistrant.registerWith`, which wraps each
// plugin's registration in `try { ... } catch (Exception)`. FFmpegKit
// (com.antonkarpenko.ffmpegkit.FFmpegKitFlutterPlugin) runs
// `System.loadLibrary("ffmpegkit_abidetect")` from a static initializer reached
// via its `onAttachedToActivity`. When the .so is incompatible with the runtime
// (e.g. Android 15+ 16KB-page emulators throw "Bad JNI version returned from
// JNI_OnLoad"), the resulting UnsatisfiedLinkError is wrapped in a
// `java.lang.Error` — which is NOT caught by `catch (Exception)` — so the
// auto-registrant aborts at FFmpegKit and every plugin after it alphabetically
// (file_picker, firebase_*, image_picker, isar, path_provider,
// shared_preferences, url_launcher, video_player, webview, workmanager, …) is
// never registered. SharedPreferences.getInstance() then throws
// `PlatformException(channel-error,
// "dev.flutter.pigeon.shared_preferences_android.SharedPreferencesApi.getAll")`
// at app start. No proguard rule can fix this — the classes are in the APK,
// the plugin is just never instantiated.
//
// Replicating the generated list here and catching `Throwable` per plugin makes
// startup resilient: a broken plugin logs an error but cannot take down the
// rest of the app.
//
// Keep `PLUGIN_CLASS_NAMES` in sync with
// `android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java`
// (regenerated by `flutter pub get`). When a plugin is added or removed from
// pubspec.yaml, mirror the change here.
class MainActivity : FlutterActivity() {
    // The intent that cold-launched the app. When a killed-state FCM
    // notification is tapped, its `data` payload arrives as extras on this
    // intent. We expose it to Dart because FlutterFirebaseMessagingPlugin's
    // getInitialMessage() returns null here (the manual plugin registration
    // below doesn't feed it the launch intent).
    private var launchIntent: Intent? = null
    private var launchNotificationConsumed = false

    override fun onCreate(savedInstanceState: android.os.Bundle?) {
        // Capture the launch intent BEFORE super.onCreate (which configures the
        // engine and starts Dart main()), so the channel can read it race-free.
        launchIntent = intent
        super.onCreate(savedInstanceState)
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        // A tap that resumes the app (warm) also routes here.
        launchIntent = intent
        launchNotificationConsumed = false
        setIntent(intent)
    }

    override fun configureFlutterEngine(flutterEngine: FlutterEngine) {
        for (fqcn in PLUGIN_CLASS_NAMES) {
            try {
                val plugin =
                    Class.forName(fqcn).getDeclaredConstructor().newInstance() as FlutterPlugin
                flutterEngine.plugins.add(plugin)
            } catch (t: Throwable) {
                Log.e(TAG, "Failed to register plugin $fqcn", t)
            }
        }

        MethodChannel(flutterEngine.dartExecutor.binaryMessenger, NOTIF_CHANNEL)
            .setMethodCallHandler { call, result ->
                if (call.method == "getInitialNotificationData") {
                    result.success(consumeLaunchNotificationData())
                } else {
                    result.notImplemented()
                }
            }
    }

    /// Returns the FCM `data` payload of the notification that launched the app
    /// (once), or null. Skips Firebase/system extras and requires an `action`.
    private fun consumeLaunchNotificationData(): Map<String, String>? {
        if (launchNotificationConsumed) return null
        val extras = launchIntent?.extras ?: run {
            Log.d(TAG, "[notif] launch intent has NO extras")
            return null
        }
        Log.d(TAG, "[notif] launch intent extras keys: ${extras.keySet().joinToString()}")
        val data = HashMap<String, String>()
        for (key in extras.keySet()) {
            if (key.startsWith("google.") ||
                key.startsWith("gcm.") ||
                key == "from" ||
                key == "collapse_key" ||
                key == "message_type" ||
                key == "sent_time" ||
                key == "ttl"
            ) {
                continue
            }
            val value = extras.get(key)
            if (value is String) data[key] = value
        }
        if (!data.containsKey("action")) return null
        launchNotificationConsumed = true
        return data
    }

    companion object {
        private const val TAG = "MainActivity"
        private const val NOTIF_CHANNEL = "wowcare/notifications"

        private val PLUGIN_CLASS_NAMES =
            listOf(
                "uz.shs.better_player_plus.BetterPlayerPlugin",
                "net.cubiclab.clipboard.ClipboardPlugin",
                "io.flutter.plugins.firebase.firestore.FlutterFirebaseFirestorePlugin",
                "dev.fluttercommunity.plus.connectivity.ConnectivityPlugin",
                "dev.fluttercommunity.plus.device_info.DeviceInfoPlusPlugin",
                "com.fintasys.emoji_picker_flutter.EmojiPickerFlutterPlugin",
                "com.antonkarpenko.ffmpegkit.FFmpegKitFlutterPlugin",
                "com.mr.flutter.plugin.filepicker.FilePickerPlugin",
                "io.flutter.plugins.firebase.core.FlutterFirebaseCorePlugin",
                "io.flutter.plugins.firebase.messaging.FlutterFirebaseMessagingPlugin",
                "io.flutter.plugins.firebase.storage.FlutterFirebaseStoragePlugin",
                "com.pichillilorenzo.flutter_inappwebview_android.InAppWebViewFlutterPlugin",
                "io.endigo.plugins.pdfviewflutter.PDFViewFlutterPlugin",
                "io.flutter.plugins.flutter_plugin_android_lifecycle.FlutterAndroidLifecyclePlugin",
                "studio.midoridesign.gal.GalPlugin",
                "com.baseflow.geocoding.GeocodingPlugin",
                "com.baseflow.geolocator.GeolocatorPlugin",
                "com.dexterous.flutterlocalnotifications.FlutterLocalNotificationsPlugin",
                "io.flutter.plugins.imagepicker.ImagePickerPlugin",
                "dev.isar.isar_flutter_libs.IsarFlutterLibsPlugin",
                "com.crazecoder.openfile.OpenFilePlugin",
                "dev.fluttercommunity.plus.packageinfo.PackageInfoPlugin",
                "io.flutter.plugins.pathprovider.PathProviderPlugin",
                "io.scer.pdfx.PdfxPlugin",
                "com.baseflow.permissionhandler.PermissionHandlerPlugin",
                "net.touchcapture.qr.flutterqrplus.FlutterQrPlusPlugin",
                "io.flutter.plugins.sharedpreferences.SharedPreferencesPlugin",
                "io.flutter.plugins.urllauncher.UrlLauncherPlugin",
                "io.flutter.plugins.videoplayer.VideoPlayerPlugin",
                "xyz.justsoft.video_thumbnail.VideoThumbnailPlugin",
                "dev.fluttercommunity.plus.wakelock.WakelockPlusPlugin",
                "io.flutter.plugins.webviewflutter.WebViewFlutterPlugin",
                "dev.fluttercommunity.workmanager.WorkmanagerPlugin",
            )
    }
}
