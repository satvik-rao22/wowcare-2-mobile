/// First non-empty (trimmed) string from [values], or '' if none — the avatar-field resolution
/// mirrors web's pickString(), so mobile reads the same photo fields the backend actually sends.
String _pickNonEmpty(List<String?> values) {
  for (final v in values) {
    if (v != null && v.trim().isNotEmpty) return v;
  }
  return '';
}

/// `DateTime.parse` with a now-fallback when absent — matches the old
/// `_parseDate` / `parse(x ?? now.toIso8601String())` helpers.
DateTime _parseDateOrNow(Object? value) =>
    value != null ? DateTime.parse(value as String) : AppTime.nowUtc();

/// Lenient nullable parse (`tryParse` when present) — matches the old
/// `lastMessageAt`/`privateModeActivatedAt` handling.
DateTime? _tryParseOrNull(Object? value) =>
    value != null ? DateTime.tryParse(value as String) : null;

// ── Field-quirk readers (were inline expressions) ───────────────────────────

Object? _readConvTitle(Map<dynamic, dynamic> json, String key) {
  final studentName = (json['studentName'] as String?)?.trim();
  final rawTitle = (json['title'] as String?)?.trim() ?? '';
  return (studentName != null && studentName.isNotEmpty)
      ? studentName
      : rawTitle;
}

Object? _readConvAvatar(Map<dynamic, dynamic> json, String key) {
  final student = json['student'] as Map<String, dynamic>?;
  return _pickNonEmpty([
    json['avatarUrl'] as String?,
    student?['photoUrl'] as String?,
    student?['avatarUrl'] as String?,
    student?['profileAssetCode'] as String?,
  ]);
}

Object? _readPartUserName(Map<dynamic, dynamic> json, String key) =>
    (json['displayName'] as String?)?.isNotEmpty == true
    ? json['displayName'] as String
    : (json['userName'] as String? ?? '');

Object? _readPartRole(Map<dynamic, dynamic> json, String key) =>
    (json['participantType'] as String?)?.isNotEmpty == true
    ? json['participantType'] as String
    : (json['role'] as String? ?? 'PARENT');

Object? _readPartAvatar(Map<dynamic, dynamic> json, String key) => _pickNonEmpty([
  json['photoUrl'] as String?,
  json['avatarUrl'] as String?,
  (json['user'] as Map<String, dynamic>?)?['photoUrl'] as String?,
  json['profileAssetCode'] as String?,
  json['profilePhotoAssetCode'] as String?,
]);

/// API response DTO for a conversation (v2 stack). Serialisation generated by
/// `json_serializable`; the `readValue`/converter helpers above and the
/// `@JsonKey` defaults reproduce the previous hand-written parser exactly,
/// including the `includeIfNull: false` omissions in `toJson`.
@JsonSerializable(explicitToJson: true)
class ConversationEntityDto {
  const ConversationEntityDto({
    required this.id,
    required this.code,
    required this.title,
    required this.type,
    required this.organizationCode,
    required this.schoolCode,
    required this.status,
    required this.description,
    required this.avatarUrl,
    required this.createdAt,
    required this.createdBy,
    required this.updatedAt,
    required this.updatedBy,
    required this.participantCount,
    required this.unreadCount,
    required this.lastMessagePreview,
    required this.participants,
    this.studentCode,
    this.studentStatus,
    this.classroomCode,
    this.lastMessageAt,
    this.lastMessageBy,
    this.lastMessageSenderName,
    this.privateModeActive = false,
    this.privateModeActivatedBy,
    this.privateModeActivatedAt,
    this.privateModeStates = const [],
  });

  @JsonKey(defaultValue: 0)
  final int id;
  @JsonKey(defaultValue: '')
  final String code;
  @JsonKey(readValue: _readConvTitle)
  final String title;
  @JsonKey(defaultValue: 'ROOM_CHAT')
  final String type;
  @JsonKey(defaultValue: '')
  final String organizationCode;
  @JsonKey(defaultValue: '')
  final String schoolCode;
  @JsonKey(defaultValue: 'ACTIVE')
  final String status;
  @JsonKey(defaultValue: '')
  final String description;
  @JsonKey(readValue: _readConvAvatar)
  final String avatarUrl;
  @JsonKey(fromJson: _parseDateOrNow)
  final DateTime createdAt;
  @JsonKey(defaultValue: '')
  final String createdBy;
  @JsonKey(fromJson: _parseDateOrNow)
  final DateTime updatedAt;
  @JsonKey(defaultValue: '')
  final String updatedBy;
  @JsonKey(defaultValue: 0)
  final int participantCount;
  @JsonKey(defaultValue: 0)
  final int unreadCount;
  @JsonKey(defaultValue: '')
  final String lastMessagePreview;
  @JsonKey(defaultValue: [])
  final List<ParticipantEntityDto> participants;
  @JsonKey(includeIfNull: false)
  final String? studentCode;
  @JsonKey(includeIfNull: false)
  final String? studentStatus;
  @JsonKey(includeIfNull: false)
  final String? classroomCode;
  @JsonKey(fromJson: _tryParseOrNull, includeIfNull: false)
  final DateTime? lastMessageAt;
  @JsonKey(includeIfNull: false)
  final String? lastMessageBy;
  @JsonKey(includeIfNull: false)
  final String? lastMessageSenderName;
  @JsonKey(defaultValue: false)
  final bool privateModeActive;
  @JsonKey(includeIfNull: false)
  final String? privateModeActivatedBy;
  @JsonKey(fromJson: _tryParseOrNull, includeIfNull: false)
  final DateTime? privateModeActivatedAt;
  @JsonKey(defaultValue: [])
  final List<PrivateModeStateDto> privateModeStates;

  factory ConversationEntityDto.fromJson(Map<String, dynamic> json) =>
      _$ConversationEntityDtoFromJson(json);

  Map<String, dynamic> toJson() => _$ConversationEntityDtoToJson(this);

  /// Maps this DTO to the domain [ConversationEntity].
  ConversationEntity toEntity() {
    return ConversationEntity(
      id: id,
      code: code,
      title: title,
      type: ConversationType.fromApiString(type),
      organizationCode: organizationCode,
      schoolCode: schoolCode,
      status: status,
      description: description,
      avatarUrl: avatarUrl,
      createdAt: createdAt,
      createdBy: createdBy,
      updatedAt: updatedAt,
      updatedBy: updatedBy,
      participantCount: participantCount,
      unreadCount: unreadCount,
      lastMessagePreview: lastMessagePreview,
      participants: participants.map((e) => e.toEntity()).toList(),
      studentCode: studentCode,
      studentStatus: studentStatus,
      classroomCode: classroomCode,
      lastMessageAt: lastMessageAt,
      lastMessageBy: lastMessageBy,
      lastMessageSenderName: lastMessageSenderName,
      privateModeActive: privateModeActive,
      privateModeActivatedBy: privateModeActivatedBy,
      privateModeActivatedAt: privateModeActivatedAt,
      privateModeStates: {
        for (final s in privateModeStates) s.parentCode: s.toEntity(),
      },
    );
  }
}

@JsonSerializable()
class ParticipantEntityDto {
  const ParticipantEntityDto({
    required this.id,
    required this.conversationId,
    required this.userCode,
    required this.userName,
    required this.role,
    required this.joinedAt,
    required this.muted,
    required this.notificationsEnabled,
    required this.createdAt,
    required this.updatedAt,
    this.leftAt,
    this.lastReadAt,
    this.avatarUrl,
    this.staffCode,
    this.guardianCode,
    this.adminCode,
    this.organizationCode,
    this.schoolCode,
    this.unreadCount = 0,
    this.active = true,
    this.staffStatus,
  });

  @JsonKey(defaultValue: 0)
  final int id;
  @JsonKey(defaultValue: 0)
  final int conversationId;
  @JsonKey(defaultValue: '')
  final String userCode;
  @JsonKey(readValue: _readPartUserName)
  final String userName;
  @JsonKey(readValue: _readPartRole)
  final String role;
  @JsonKey(readValue: _readPartAvatar)
  final String? avatarUrl;
  @JsonKey(fromJson: _parseDateOrNow)
  final DateTime joinedAt;
  @JsonKey(includeIfNull: false)
  final DateTime? leftAt;
  @JsonKey(includeIfNull: false)
  final DateTime? lastReadAt;
  @JsonKey(defaultValue: false)
  final bool muted;
  @JsonKey(defaultValue: true)
  final bool notificationsEnabled;
  @JsonKey(fromJson: _parseDateOrNow)
  final DateTime createdAt;
  @JsonKey(fromJson: _parseDateOrNow)
  final DateTime updatedAt;
  // Not currently sent by the backend participant payload — parsed
  // defensively so they populate the moment the backend adds them, with no
  // further Flutter changes required. Until then these are always null.
  @JsonKey(includeIfNull: false)
  final String? staffCode;
  @JsonKey(includeIfNull: false)
  final String? guardianCode;
  @JsonKey(includeIfNull: false)
  final String? adminCode;
  @JsonKey(includeIfNull: false)
  final String? organizationCode;
  @JsonKey(includeIfNull: false)
  final String? schoolCode;

  /// This participant's own unread count — the real, per-user signal on the
  /// list response (the conversation-level `unreadCount` field is never
  /// actually populated by the backend). See toEntity() usage note.
  @JsonKey(defaultValue: 0)
  final int unreadCount;

  /// Backend-authoritative "still active" flag — sent alongside (and
  /// independent of) `leftAt`; a participant can be deactivated without
  /// `leftAt` being set (e.g. `deactivatedReason`).
  @JsonKey(defaultValue: true)
  final bool active;

  /// This participant's own employment status (`ACTIVE`/`UPCOMING`/
  /// `INACTIVE`) when they're a staff member — the STAFF_DIRECT
  /// equivalent of the conversation-level `studentStatus`.
  @JsonKey(includeIfNull: false)
  final String? staffStatus;

  factory ParticipantEntityDto.fromJson(Map<String, dynamic> json) =>
      _$ParticipantEntityDtoFromJson(json);

  Map<String, dynamic> toJson() => _$ParticipantEntityDtoToJson(this);

  ParticipantEntity toEntity() {
    return ParticipantEntity(
      id: id,
      conversationId: conversationId,
      userCode: userCode,
      userName: userName,
      role: ParticipantRole.fromApiString(role),
      avatarUrl: avatarUrl,
      joinedAt: joinedAt,
      leftAt: leftAt,
      lastReadAt: lastReadAt,
      muted: muted,
      notificationsEnabled: notificationsEnabled,
      createdAt: createdAt,
      updatedAt: updatedAt,
      staffCode: staffCode,
      guardianCode: guardianCode,
      adminCode: adminCode,
      organizationCode: organizationCode,
      schoolCode: schoolCode,
      unreadCount: unreadCount,
      active: active,
      staffStatus: staffStatus,
    );
  }
}

