  factory StudentDataModel.fromMap(DataMap map) {
    return StudentDataModel(
      id: map['id'] as int? ?? 0,
      fullName: map['fullName'] as String? ?? '',
      photoUuid: map['photoUuid'] as String? ?? '',
      gender: map['gender'] as String?,
      bloodGroup: map['bloodGroup'] as String?,
      studentUniqueId: map['studentUniqueId'] as String?,
      dateOfBirth: map['dateOfBirth'] as String? ?? '',
      isSignedIn: map['isSignedIn'] as bool? ?? false,
      isAbsent: map['isAbsent'] as bool? ?? false,
      isExpectedToday: map['isExpectedToday'] as bool? ?? false,
      isPresentToday: map['isPresentToday'] as bool? ?? false,
      napStartOrEnd: map['napStartOrEnd'] as String? ?? '',
      movementDate: map['movementDate'] as String? ?? '',
      studentFte: map['studentFte'] as double?,
      foodProgram: map['foodProgram'] as String?,
      registrationDate: map['registrationDate'] as String? ?? '',
      leavingDate: map['leavingDate'] as String?,
      roomStartDate: map['roomStartDate'] as String?,
      profileStatus: map['profileStatus'] as String? ?? '',
      allergies: map['allergies'] as String? ?? '',
      medications: map['medications'] as String? ?? '',
      dietRestriction: map['dietRestriction'] as String? ?? '',
      isPhotoPermission: map['isPhotoPermission'] as bool? ?? false,
      note: map['note'] as String? ?? '',
      roomId: map['roomId'] as int? ?? 0,
      status: map['status'] as String? ?? '',
      schoolId: map['schoolId'] as int? ?? 0,
      lastModified: map['lastModified'] as String? ?? '',
      lastModifiedBy: map['lastModifiedBy'] as String? ?? '',
      hasPrivateChat: map['hasPrivateChat'] as bool? ?? false,
      isTagRemoved: map['isTagRemoved'] as bool?,
      privatedByGuardian: map['privatedByGuardian'] as int?,
      subsidyInvoiced: map['subsidyInvoiced'] as double? ?? 0.0,
      subsidyBalance: map['subsidyBalance'] as double? ?? 0.0,
      subsidyReceived: map['subsidyReceived'] as double? ?? 0.0,
      childCustody: map['childCustody'] as String?,
      startDate: map['startDate'] as String?,
      expectedMoveDate: map['expectedMoveDate'] as String?,
      isStateSubsidyAllowed: map['isStateSubsidyAllowed'] as bool? ?? false,
      tags:
          (map['tags'] as List<dynamic>?)
              ?.map<Tag>((x) => TagModel.fromMap(x as DataMap))
              .toList() ??
          [],

      siblings: (map['siblings'] as List<dynamic>?)?.cast<String>() ?? [],
      activities:
          (map['activities'] as List<dynamic>?)
              ?.map<ActivityEntity>((x) => ActivityModel.fromMap(x as DataMap))
              .toList() ??
          [],

      schedule:
          (map['schedule'] as List<dynamic>?)
              ?.map<ScheduleDataModel>(
                (x) => ScheduleDataModel.fromMap(x as DataMap),
              )
              .toList() ??
          [],
      transactions:
          (map['transactions'] as List<dynamic>?)
              ?.map<TransactionDTO>((x) => TransactionDTO.fromMap(x as DataMap))
              .toList() ??
          [],
      programRoom: map['programRoom'] as String?,
      openBalance: map['openBalance'] as double? ?? 0.0,
      roomName: map['roomName'] as String? ?? '',
      invoice:
          (map['invoice'] as List<dynamic>?)
              ?.map<InvoiceDTO>((x) => InvoiceDTO.fromMap(x as DataMap))
              .toList() ??
          [],
      students: (map['students'] as List<dynamic>?)?.cast<int>() ?? [],
      recurringPlan:
          (map['recurringPlan'] as List<dynamic>?)?.cast<String>() ?? [],
      paymentMode: map['paymentMode'] as String?,
    );
  }

