enum ReportType {
  // Student Attendance (4 types)
  studentDailyAttendance('STUDENT_DAILY_ATTENDANCE'),
  studentAbsent('STUDENT_ABSENT'),
  studentAttendancePerStudent('STUDENT_ATTENDANCE_PER_STUDENT'),

  // Staff Attendance (3 types)
  staffAbsent('STAFF_ABSENT'),
  staffAttendance('STAFF_ATTENDANCE'),
  staffAttendancePerStaff('STAFF_ATTENDANCE_PER_STAFF'),

  // Staff Management (1 type - staffSchedule unavailable)
  staffDetails('STAFF_DETAILS'),

  // Student Management (3 types)
  studentsAndFamily('STUDENTS_AND_FAMILY'),
  emergencyContacts('EMERGENCY_CONTACTS'),
  studentIncident('STUDENT_INCIDENT'),

  // Immunization (2 types)
  immunization('IMMUNIZATION'),
  annualStateImmunization('ANNUAL_STATE_IMMUNIZATION'),

  // Billing (6 types) — generated by the accounts microservice.
  billingTransaction('TRANSACTION'),
  billingInvoice('INVOICE'),
  billingPaymentSummary('PAYMENT_SUMMARY'),
  billingOutstanding('OUTSTANDING'),
  billingRefund('REFUND'),
  billingStudentMapping('STUDENT_BILLING_MAPPING');

  const ReportType(this.backendValue);

  final String backendValue;

  /// True for the accounts/billing report family (routed to the billing microservice).
  bool get isBilling =>
      this == billingTransaction ||
      this == billingInvoice ||
      this == billingPaymentSummary ||
      this == billingOutstanding ||
      this == billingRefund ||
      this == billingStudentMapping;
}
