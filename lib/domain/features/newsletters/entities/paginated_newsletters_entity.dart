import 'package:equatable/equatable.dart';

import 'newsletter_entity.dart';

class PaginatedNewslettersEntity extends Equatable {
  const PaginatedNewslettersEntity({
    required this.items,
    required this.page,
    required this.size,
    required this.totalPages,
    required this.totalElements,
    required this.hasMore,
  });

  final List<NewsletterEntity> items;
  final int page;
  final int size;
  final int totalPages;
  final int totalElements;
  final bool hasMore;

  @override
  List<Object?> get props =>
      [items, page, size, totalPages, totalElements, hasMore];
}

