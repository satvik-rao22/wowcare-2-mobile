// Generates lib/core/theme/app_palette.gen.dart from the skin_*.dart files.
//
//   dart run tool/gen_palette.dart          rewrite the file
//   dart run tool/gen_palette.dart --check  exit 1 if it is stale
//
// Adding a skin: add a value to `AppSkin`, create skin_<name>.dart with a
// `<Name>Skin` class that overrides the roles that differ from the base skin,
// then run this. The first `AppSkin` value is the base and declares every
// role; a role whose value is another role's name is an alias.

import 'dart:io';

const String themeDir = 'lib/core/theme';
const String outputName = 'app_palette.gen.dart';

void main(List<String> args) {
  final String generated = generatePalette(
    config: File('$themeDir/app_theme_config.dart').readAsStringSync(),
    skins: readSkinSources(),
  );
  final File out = File('$themeDir/$outputName');
  final bool stale = !out.existsSync() || out.readAsStringSync() != generated;
  if (args.contains('--check')) {
    if (stale) {
      stderr.writeln(
        '$outputName is stale: run dart run tool/gen_palette.dart',
      );
      exit(1);
    }
    stdout.writeln('$outputName is up to date');
    return;
  }
  out.writeAsStringSync(generated);
  stdout.writeln('wrote ${out.path}');
}

/// Every `skin_*.dart` under [themeDir], keyed by path.
Map<String, String> readSkinSources() => <String, String>{
  for (final FileSystemEntity e in Directory(themeDir).listSync())
    if (e is File && _isSkinFile(e.path)) e.path: e.readAsStringSync(),
};

bool _isSkinFile(String path) {
  final String name = path.split(Platform.pathSeparator).last;
  return name.startsWith('skin_') && name.endsWith('.dart');
}

/// Builds the `AppPalette` source from the `AppSkin` enum in [config] and the
/// skin classes in [skins]. Throws a [StateError] on a skin without an enum
/// value, an enum value without a skin, or an override of an unknown role.
String generatePalette({
  required String config,
  required Map<String, String> skins,
}) {
  final List<String> enumValues = _enumValues(config);
  final String baseName = enumValues.first;

  final Map<String, _Skin> byEnum = <String, _Skin>{};
  for (final MapEntry<String, String> e in skins.entries) {
    final _Skin skin = _Skin.parse(e.key, e.value);
    if (!enumValues.contains(skin.enumName)) {
      throw StateError(
        '${e.key}: class ${skin.className} has no AppSkin.${skin.enumName}',
      );
    }
    byEnum[skin.enumName] = skin;
  }
  for (final String v in enumValues) {
    if (!byEnum.containsKey(v)) {
      throw StateError('AppSkin.$v has no skin_*.dart file');
    }
  }

  final _Skin base = byEnum[baseName]!;
  final Set<String> roleNames = base.roles.map((_Role r) => r.name).toSet();
  for (final String v in enumValues.skip(1)) {
    final Iterable<String> unknown = byEnum[v]!.roles
        .map((_Role r) => r.name)
        .where((String n) => !roleNames.contains(n));
    if (unknown.isNotEmpty) {
      throw StateError(
        '${byEnum[v]!.className} overrides roles the base skin does not '
        'declare: ${unknown.join(', ')}',
      );
    }
  }

  final StringBuffer out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_palette.dart from $themeDir/skin_*.dart.',
    )
    ..writeln(
      '// Do not edit. After changing a skin: dart run tool/gen_palette.dart',
    )
    ..writeln()
    ..writeln("part of 'app_theme_config.dart';")
    ..writeln()
    ..writeln('const AppSkin _skin = AppThemeConfig.skin;')
    ..writeln()
    ..writeln(
      '/// The app\'s colours by meaning. Each role resolves at compile time to',
    )
    ..writeln(
      '/// the active skin\'s value. Product code reads these; the skins hold',
    )
    ..writeln('/// the values.')
    ..writeln('abstract final class AppPalette {');

  for (final _Line line in base.body) {
    if (line.role == null) {
      out.writeln(line.text);
      continue;
    }
    final _Role role = line.role!;
    for (final String doc in role.docs) {
      out.writeln(doc);
    }
    final List<String> pieces = <String>[];
    for (final String v in enumValues.skip(1)) {
      if (byEnum[v]!.has(role.name)) {
        pieces
          ..add('_skin == AppSkin.$v')
          ..add('${byEnum[v]!.className}.${role.name}');
      }
    }
    final String fallback = roleNames.contains(role.expr)
        ? role.expr
        : '${base.className}.${role.name}';
    out.writeln(_declaration(role.name, pieces, fallback));
  }
  out.writeln('}');
  return out.toString();
}

/// One declaration, laid out the way `dart format` lays out a conditional:
/// on one line when it fits in 80 columns, otherwise one branch per line.
String _declaration(String name, List<String> pieces, String fallback) {
  final String head = '  static const Color $name = ';
  if (pieces.isEmpty) return '$head$fallback;';
  final StringBuffer one = StringBuffer(head);
  for (int i = 0; i < pieces.length; i += 2) {
    one.write('${pieces[i]} ? ${pieces[i + 1]} : ');
  }
  one.write('$fallback;');
  if (one.length <= 80) return one.toString();

  final StringBuffer many = StringBuffer('$head${pieces[0]}');
  for (int i = 0; i < pieces.length; i += 2) {
    many.write('\n      ? ${pieces[i + 1]}');
    many.write(i + 2 < pieces.length ? '\n      : ${pieces[i + 2]}' : '');
  }
  many.write('\n      : $fallback;');
  return many.toString();
}

List<String> _enumValues(String config) {
  final RegExpMatch? m = RegExp(
    r'enum AppSkin\s*\{([^}]*)\}',
  ).firstMatch(config);
  if (m == null) throw StateError('enum AppSkin not found in config');
  return m
      .group(1)!
      .split('\n')
      .map((String l) => l.replaceFirst(RegExp(r'//.*'), ''))
      .join()
      .split(',')
      .map((String s) => s.trim())
      .where((String s) => s.isNotEmpty)
      .toList();
}

class _Skin {
  _Skin(this.className, this.body);

  final String className;

  /// The class body, line by line; comment and blank lines are kept so the
  /// base skin's layout carries into the generated palette.
  final List<_Line> body;

  String get enumName {
    final String stem = className.substring(0, className.length - 4);
    return stem[0].toLowerCase() + stem.substring(1);
  }

  Iterable<_Role> get roles =>
      body.where((_Line l) => l.role != null).map((_Line l) => l.role!);

  bool has(String role) => roles.any((_Role r) => r.name == role);

  static _Skin parse(String path, String source) {
    final RegExpMatch? cls = RegExp(
      r'abstract final class (\w+Skin)\s*\{\n(.*?)\n\}',
      dotAll: true,
    ).firstMatch(source);
    if (cls == null) {
      throw StateError('$path: no `abstract final class <Name>Skin` found');
    }
    final List<_Line> body = <_Line>[];
    final List<String> docs = <String>[];
    final List<String> lines = cls.group(2)!.split('\n');
    for (int i = 0; i < lines.length; i++) {
      final String line = lines[i];
      final String t = line.trim();
      if (t.startsWith('///')) {
        docs.add(line);
        continue;
      }
      final RegExpMatch? m = RegExp(
        r'static const Color (\w+) =(.*)',
      ).firstMatch(t);
      if (m == null) {
        body.add(_Line(line));
        continue;
      }
      String expr = m.group(2)!;
      while (!expr.trimRight().endsWith(';')) {
        expr += ' ${lines[++i].trim()}';
      }
      expr = expr.trim();
      expr = expr.substring(0, expr.length - 1).trim();
      body.add(_Line(line, _Role(m.group(1)!, expr, List<String>.of(docs))));
      docs.clear();
    }
    return _Skin(cls.group(1)!, body);
  }
}

class _Line {
  _Line(this.text, [this.role]);
  final String text;
  final _Role? role;
}

class _Role {
  _Role(this.name, this.expr, this.docs);
  final String name;
  final String expr;
  final List<String> docs;
}
